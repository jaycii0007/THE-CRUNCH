import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const read = (file) => fs.readFileSync(new URL('../src/' + file, import.meta.url), 'utf8');
const source = read('components/included-menu-selections.tsx');
let slots = [], cursor = 0, chosen;
const exports = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText, { exports, require(id) {
 if (id === 'react') return { useState(initial) { const index = cursor++; if (!(index in slots)) slots[index] = initial; return [slots[index], value => { slots[index] = typeof value === 'function' ? value(slots[index]) : value; }]; } };
 return require(id);
} });
const all = node => Array.isArray(node) ? node.flatMap(all) : node?.props ? [node, ...all(node.props.children)] : [];
const props = { name: 'Meal', config: { drinks: { enabled: true, includedQuantity: 1 }, 'category:9': { enabled: true, includedQuantity: 1, label: 'Extra Sauce', sauce: true } }, options: [{ id: 7, name: 'Sauce cup', categoryKey: 'category:9', available: true, stock: 5 }], onConfirm(value) { chosen = value; }, onCancel() {} };
const render = () => { cursor = 0; return exports.IncludedSelectionModal(props); };
let tree = render();
assert.equal(all(tree).filter(node => node.type === 'select').length, 1);
assert.ok(!all(tree).some(node => node.props['aria-label'] === 'Required Chicken Flavor'));
all(tree).find(node => node.type === 'select').props.onChange({ target: { value: '7' } });
tree = render();
const add = all(tree).find(node => node.props.children === 'Add to cart');
assert.equal(add.props.disabled, false); add.props.onClick();
assert.equal(chosen[0].kind, 'category:9'); assert.equal(chosen[0].qty, 1);
props.config = { drinks: { enabled: true, includedQuantity: 1 } };
assert.equal(exports.hasIncludedChoices(props.config), false);
assert.equal(all(render()).filter(node => node.type === 'select').length, 0);
const management = read('pages/inventory.tsx');
assert.match(management, /Configure included items for this menu product/);
assert.doesNotMatch(management, /Existing Drink\/Sauce|Existing \{key\}/);
assert.doesNotMatch(read('pages/settings.tsx'), /sauceTriggerIds|Sauces ? ingredient triggers/);
for (const page of ['menu.tsx','usersmenu.tsx']) assert.match(read('pages/' + page), /requiresSauce: false/);
console.log('Dynamic-only popup, one Extra Sauce selector, legacy ignored, zero-price payload and retired trigger UI passed.');
