import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import { createRequire } from "node:module";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import ts from "typescript";
const require = createRequire(import.meta.url);
const source = fs.readFileSync(new URL("../src/components/ui/skeleton.tsx", import.meta.url), "utf8");
const context = { exports: {}, require(id) { return id === "@/lib/utils" ? { cn: (...values) => values.filter(Boolean).join(" ") } : require(id); } };
vm.createContext(context);
const options = { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 };
vm.runInContext(ts.transpileModule(source, { compilerOptions: options }).outputText, context);
const staff = fs.readFileSync(new URL("../src/pages/staffaccounts.tsx", import.meta.url), "utf8");
const syntax = ts.transpileModule(staff, { fileName: "staffaccounts.tsx", compilerOptions: options, reportDiagnostics: true });
assert.equal((syntax.diagnostics ?? []).filter((d) => d.category === ts.DiagnosticCategory.Error).length, 0);
const start = staff.indexOf("{isLoading ? (", staff.indexOf("<tbody>"));
const end = staff.indexOf(") : filteredEmployees", start);
assert.ok(start > 0 && end > start);
const expression = staff.slice(start + "{isLoading ? (".length, end);
const rows = { exports: {}, SkeletonTableRow: context.exports.SkeletonTableRow, require };
vm.createContext(rows);
vm.runInContext(ts.transpileModule(`exports.rows = (${expression});`, { compilerOptions: options }).outputText, rows);
const html = renderToStaticMarkup(React.createElement("table", null, React.createElement("tbody", null, rows.exports.rows)));
assert.match(html, /<tbody><tr/);
assert.equal((html.match(/<tr\b/g) ?? []).length, 5);
assert.equal((html.match(/<td\b/g) ?? []).length, 35);
assert.equal((html.match(/<table\b/g) ?? []).length, 1);
assert.match(html, /padding:14px 16px/);
console.log("Staff Accounts skeleton: valid five-row/seven-column markup and TSX syntax passed.");
